/* crashdump.h - 崩溃转储
 * ============================================================================
 * 用户报"它崩了"时，光有一句"崩了"什么都查不出来：没有异常地址、没有调用栈，
 * 也没法确认是哪个版本。这里在程序启动时装一个"最后一道网"：
 * 未处理异常发生时，把当时的内存现场写成一个 .dmp 文件（拖进 WinDbg / VS 就能看栈），
 * 再写一份同名的 .txt 摘要（版本、异常码、地址），用户直接把 txt 贴在 issue 里就够了。
 *
 * 为什么不挂调试器、也不做"自动上报"：
 *   - 挂调试器要额外进程，杀软会当成可疑行为；
 *   - 自动上报要服务器、要隐私声明，而这个项目只是一本本地阅读器。
 * 所以：只落地在本地，只保留最近 5 份，用户愿意就给，不愿意就算了。
 * ============================================================================ */
#ifndef NR_CRASHDUMP_H
#define NR_CRASHDUMP_H

#include <string>

/* 装未处理异常过滤器。在 wWinMain 里尽早调用一次即可，重复调用无害。 */
void CrashDumpInstall();

/* 崩溃目录（%LOCALAPPDATA%\NovelReader\crashes）。界面里"打开崩溃文件夹"用它。 */
std::wstring CrashDumpDir();

#endif /* NR_CRASHDUMP_H */
